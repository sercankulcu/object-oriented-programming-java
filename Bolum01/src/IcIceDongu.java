// Ic Ice Dongu: dis dongunun her turunda ic dongu bastan sona doner.
public class IcIceDongu {
	public static void main(String[] args) {
		for (int i = 1; i <= 2; i++) {
			for (int j = 1; j <= 3; j++) {
				System.out.print(i * j + " ");
			}
			System.out.println();
		}
		// 1 2 3
		// 2 4 6
	}
}

